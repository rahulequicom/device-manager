import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';

test('admin policies, atomic audit, uniqueness, and concurrent edits', async () => {
  const db = new PGlite();
  const admin = '11111111-1111-4111-8111-111111111111';
  const outsider = '22222222-2222-4222-8222-222222222222';
  try {
    await db.exec(`create role anon; create role authenticated;
      create schema auth;
      create table auth.users (id uuid primary key, email text);
      create function auth.uid() returns uuid language sql stable as
      $$ select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $$;
      grant usage on schema public, auth to authenticated, anon;
      insert into auth.users values ('${admin}', 'admin@example.test'), ('${outsider}', 'other@example.test');`);
    await db.exec(await readFile(new URL('../../supabase/migrations/202610140001_device_register.sql', import.meta.url), 'utf8'));
    await db.exec(await readFile(new URL('../../supabase/migrations/202610140002_device_platform.sql', import.meta.url), 'utf8'));
    await db.query('insert into dm_admins(user_id) values ($1)', [admin]);
    await db.exec('set role anon');
    await assert.rejects(db.query('select * from dm_devices'), /permission denied/);
    await db.exec('reset role; set role authenticated');
    await db.query("select set_config('request.jwt.claim.sub', $1, false)", [outsider]);
    assert.equal((await db.query('select * from dm_devices')).rows.length, 0);
    await assert.rejects(db.query("insert into dm_members(name,team) values ('Test person','QA')"), /row-level security/);
    await assert.rejects(db.query('insert into dm_admins(user_id) values ($1)', [outsider]), /permission denied/);
    await db.query("select set_config('request.jwt.claim.sub', $1, false)", [admin]);
    const member = (await db.query("insert into dm_members(name,team) values ('Test person','QA') returning id")).rows[0];
    const device = (await db.query("insert into dm_devices(name,model_name,serial_number,capacity,barcode) values ('Test phone','iPhone',' serial-1 ','128 GB','box-1') returning *")).rows[0];
    assert.equal(device.serial_number, 'SERIAL-1');
    assert.equal(device.version, 1);
    await assert.rejects(db.query("insert into dm_devices(name,model_name,serial_number,capacity,barcode) values ('Duplicate','iPhone','serial-1','128 GB','box-2')"), /unique/);
    const assigned = await db.query('update dm_devices set holder_id=$1 where id=$2 and version=1 returning version', [member.id, device.id]);
    assert.equal(assigned.rows[0].version, 2);
    assert.equal((await db.query('update dm_devices set holder_id=null where id=$1 and version=1 returning id', [device.id])).rows.length, 0);
    await assert.rejects(db.query('update dm_devices set retired=true where id=$1', [device.id]), /dm_retired_devices_unassigned/);
    await assert.rejects(db.query('update dm_devices set version=99 where id=$1', [device.id]), /permission denied/);
    await assert.rejects(db.query("update dm_audit_events set actor='Forged'"), /permission denied/);
    const audit = (await db.query('select * from dm_audit_events order by created_at')).rows;
    assert.equal(audit.length, 2);
    assert.equal(audit[1].actor, 'admin@example.test');
    assert.match(audit[1].action, /Assigned to Test person/);
    assert.equal(audit[1].before_data.holder_id, null);
    assert.equal(audit[1].after_data.holder_id, member.id);
    await db.query('update dm_devices set holder_id=null where id=$1 and version=2', [device.id]);
    await db.query('update dm_devices set retired=true where id=$1 and version=3', [device.id]);
    assert.equal((await db.query('select count(*)::int as count from dm_audit_events')).rows[0].count, 4);
    const initial = (await db.query("insert into dm_devices(name,model_name,serial_number,barcode,capacity,platform,holder_id) values ('Android phone','Pixel','ANDROID-1','ANDROID-1','128 GB','Android',$1) returning *", [member.id])).rows[0];
    assert.equal(initial.platform, 'Android');
    assert.equal(initial.holder_id, member.id);
    await assert.rejects(db.query("update dm_devices set platform='Other' where id=$1", [initial.id]), /check constraint/);
    await db.exec('reset role');
    const shipping = await readFile(new URL('../../supabase/migrations/202610140003_ship_inventory.sql', import.meta.url), 'utf8');
    await db.exec(shipping);
    await db.exec(shipping);
    const imported = (await db.query("select * from dm_devices where barcode like 'EQ-%'")).rows;
    assert.equal(imported.length, 12);
    assert.equal(imported.filter(row => row.platform === 'iOS').length, 2);
    assert.equal(imported.filter(row => row.allocation_team === 'QA').length, 9);
    assert.equal(imported.filter(row => row.serial_number === null).length, 6);
    assert.ok(imported.every(row => row.holder_id === null && row.availability_confirmed === false));
    const mobileSync = await readFile(new URL('../../supabase/migrations/202610140004_mobile_sync.sql', import.meta.url), 'utf8');
    await db.exec(mobileSync);
    const rescanSafety = await readFile(new URL('../../supabase/migrations/202610140005_mobile_rescan_safety.sql', import.meta.url), 'utf8');
    await db.exec(rescanSafety);
    const duplicateCheck = await readFile(new URL('../../supabase/migrations/202610140006_mobile_duplicate_check.sql', import.meta.url), 'utf8');
    await db.exec(duplicateCheck);
    const mobileInventory = await readFile(new URL('../../supabase/migrations/202610140007_mobile_inventory_sync.sql', import.meta.url), 'utf8');
    await db.exec(mobileInventory);
    await db.exec('set role anon');
    await db.query("insert into dm_mobile_scans(source_device_id,name,model_name,model_number,serial_number,ios_version,platform,capacity,barcode,imei,imei2,eid,upc) values ('MOB-TEST','iPhone 17 Sage','iPhone 17','A3520','CL4DY7FPWV','Awaiting device sync','iOS','256 GB','CL4DY7FPWV','354630188437582','354630188535286','8904903202000884800235132661369','195950644241')");
    await assert.rejects(db.query('select * from dm_mobile_scans'), /permission denied/);
    await db.exec('reset role; set role authenticated');
    await db.query("select set_config('request.jwt.claim.sub', $1, false)", [admin]);
    assert.equal((await db.query('select dm_import_mobile_scans() as imported')).rows[0].imported, 1);
    const synced = (await db.query("select barcode, imei, imei2, eid, upc from dm_devices where serial_number='CL4DY7FPWV'")).rows[0];
    assert.equal(synced.barcode, 'EQ-005');
    assert.equal(synced.imei, '354630188437582');
    assert.equal(synced.imei2, '354630188535286');
    assert.equal(synced.eid, '8904903202000884800235132661369');
    assert.equal(synced.upc, '195950644241');
    await db.exec('reset role; set role anon');
    const duplicate = (await db.query("select public.dm_check_mobile_identity('CL4DY7FPWV', null, null, null, null) as result")).rows[0].result;
    assert.equal(duplicate.registered, true);
    const inventory = (await db.query('select public.dm_mobile_inventory() as result')).rows[0].result;
    assert.equal(inventory.devices.filter(device => device.barcode.startsWith('EQ-')).length, 12);
    await db.exec('reset role; set role authenticated');
    await db.exec('set role authenticated');
    await db.query('update dm_devices set availability_confirmed=true where id=$1', [imported[0].id]);
    await db.query('update dm_devices set holder_id=$1 where id=$2', [member.id, imported[1].id]);
    assert.equal((await db.query('select availability_confirmed from dm_devices where id=$1', [imported[1].id])).rows[0].availability_confirmed, true);
    const nextMember = (await db.query("insert into dm_members(name,team) values ('Next holder','Design') returning id")).rows[0];
    const beforeTransfer = (await db.query('select * from dm_devices where id=$1', [imported[1].id])).rows[0];
    await db.query('update dm_devices set holder_id=$1, availability_confirmed=true where id=$2 and version=$3', [nextMember.id, beforeTransfer.id, beforeTransfer.version]);
    const transferred = (await db.query('select * from dm_devices where id=$1', [beforeTransfer.id])).rows[0];
    assert.equal(transferred.holder_id, nextMember.id);
    assert.equal(transferred.allocation_team, beforeTransfer.allocation_team);
    const transferEvent = (await db.query('select * from dm_audit_events where device_id=$1 order by created_at desc limit 1', [beforeTransfer.id])).rows[0];
    assert.match(transferEvent.action, /Transferred from Test person \/ QA to Next holder \/ Design/);
    assert.equal(transferEvent.before_data.holder_id, member.id);
    assert.equal(transferEvent.after_data.holder_id, nextMember.id);
    await db.query("select set_config('request.jwt.claim.sub', $1, false)", [outsider]);
    assert.equal((await db.query('select * from dm_devices')).rows.length, 0);
    assert.equal((await db.query('select * from dm_audit_events')).rows.length, 0);
  } finally { await db.close(); }
});
