import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile,readdir} from 'node:fs/promises';
import {PGlite} from '@electric-sql/pglite';

test('People activation, deactivation and reversible deletion enforce access on every employee RPC and preserve ownership/history',async()=>{
 const db=new PGlite();
 const admin='10000000-0000-4000-8000-000000000001',alice='10000000-0000-4000-8000-000000000002',bob='10000000-0000-4000-8000-000000000003',incoming='10000000-0000-4000-8000-000000000004';
 try{
  await db.exec(`create role anon;create role authenticated;create schema auth;
   create table auth.users(id uuid primary key,email text unique,email_confirmed_at timestamptz,raw_user_meta_data jsonb default '{}',encrypted_password text default 'unchanged-hash');
   create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
   grant usage on schema public,auth to anon,authenticated;
   insert into auth.users(id,email) values ('${admin}','admin@equicomtech.com'),('${alice}','alice@equicomtech.com'),('${bob}','bob@equicomtech.com');`);
  const folder=new URL('../../supabase/migrations/',import.meta.url);
  for(const file of (await readdir(folder)).filter(x=>x.endsWith('.sql')).sort())await db.exec(await readFile(new URL(file,folder),'utf8'));
  await db.query('insert into dm_admins(user_id) values ($1)',[admin]);
  const ids=[];
  for(const name of ['Admin','Alice','Bob','Incoming'])ids.push((await db.query("insert into dm_members(name,team,role) values ($1,'QA','QA Tester') returning id",[name])).rows[0].id);
  await db.query('insert into dm_employees(user_id,member_id) values ($1,$2),($3,$4),($5,$6)',[admin,ids[0],alice,ids[1],bob,ids[2]]);
  const devices=(await db.query('select * from dm_devices order by id limit 2')).rows;
  await db.query('update dm_devices set holder_id=$1 where id=$2',[ids[1],devices[0].id]);
  await db.query('update dm_devices set holder_id=$1 where id=$2',[ids[2],devices[1].id]);
  const audits=(await db.query('select count(*)::int as n from dm_audit_events')).rows[0].n;
  await db.exec('set role anon');
  await assert.rejects(db.query('select dm_admin_set_person_state($1,$2)',[ids[1],'deactivate']),/permission denied/);
  await db.exec('reset role;set role authenticated');
  await db.query("select set_config('request.jwt.claim.sub',$1,false)",[bob]);
  await assert.rejects(db.query('select dm_admin_set_person_state($1,$2)',[ids[1],'deactivate']),/Admin access/);
  await db.query("select set_config('request.jwt.claim.sub',$1,false)",[admin]);
  await assert.rejects(db.query('select dm_admin_set_person_state($1,$2)',[ids[0],'delete']),/protected/);
  await db.query('select dm_admin_set_person_state($1,$2)',[ids[1],'deactivate']);
  assert.equal((await db.query('select holder_id from dm_devices where id=$1',[devices[0].id])).rows[0].holder_id,ids[1]);
  assert.equal((await db.query('select count(*)::int as n from dm_audit_events')).rows[0].n,audits);
  await db.query("select set_config('request.jwt.claim.sub',$1,false)",[alice]);
  assert.equal((await db.query('select dm_employee_member_id() as id')).rows[0].id,null);
  const access=(await db.query('select * from dm_employee_access()')).rows[0];assert.equal(access.is_active,false);assert.equal(access.member_id,ids[1]);
  await assert.rejects(db.query('select * from dm_employee_catalog()'),/Employee access/);
  await assert.rejects(db.query('select * from dm_employee_directory()'),/Employee access/);
  await assert.rejects(db.query('select * from dm_employee_activity()'),/Employee access/);
  await assert.rejects(db.query('select dm_employee_save_profile($1,$2,null,null)',['QA','QA Tester']),/Employee access/);
  await assert.rejects(db.query('select dm_employee_self_assign($1,$2)',[devices[0].id,2]),/Employee access/);
  await assert.rejects(db.query('select dm_employee_transfer($1,$2,$3)',[devices[0].id,ids[2],2]),/Employee access/);
  await assert.rejects(db.query('update dm_members set is_active=true where id=$1',[ids[1]]),/permission denied/);
  await db.query("select set_config('request.jwt.claim.sub',$1,false)",[bob]);
  assert.ok(!(await db.query('select * from dm_employee_directory()')).rows.some(row=>row.id===ids[1]));
  await assert.rejects(db.query('select dm_employee_transfer($1,$2,$3)',[devices[1].id,ids[1],2]),/active person/);
  await db.query("select set_config('request.jwt.claim.sub',$1,false)",[admin]);
  await assert.rejects(db.query('select dm_admin_set_person_state($1,$2)',[ids[1],'delete']),/Return or transfer/);
  await db.query('update dm_devices set holder_id=null where id=$1',[devices[0].id]);
  await db.query('select dm_admin_set_person_state($1,$2)',[ids[1],'delete']);
  const deleted=(await db.query('select * from dm_members where id=$1',[ids[1]])).rows[0];assert.ok(deleted.deleted_at);assert.equal(deleted.is_active,false);
  await assert.rejects(db.query('select dm_admin_set_person_state($1,$2)',[ids[1],'activate']),/Restore/);
  await db.query('select dm_admin_set_person_state($1,$2)',[ids[1],'restore']);
  await db.query("select set_config('request.jwt.claim.sub',$1,false)",[alice]);
  assert.equal((await db.query('select dm_employee_member_id() as id')).rows[0].id,ids[1]);
  assert.equal((await db.query('select * from dm_employee_catalog()')).rows.length,12);
  await db.exec('reset role');
  assert.equal((await db.query('select count(*)::int as n from auth.users')).rows[0].n,3);
  assert.equal((await db.query('select encrypted_password from auth.users where id=$1',[alice])).rows[0].encrypted_password,'unchanged-hash');
  assert.equal((await db.query('select count(*)::int as n from dm_devices')).rows[0].n,12);
  assert.equal((await db.query('select count(*)::int as n from dm_audit_events')).rows[0].n,audits+1);
  // Status changes between preparation and signup cannot create an inactive login.
  await db.query("select set_config('request.jwt.claim.sub',$1,false)",[admin]);
  const token=(await db.query("select dm_prepare_employee_login('incoming@equicomtech.com','Incoming','QA','QA Tester',$1) as token",[ids[3]])).rows[0].token;
  await db.query('select dm_admin_set_person_state($1,$2)',[ids[3],'deactivate']);
  await assert.rejects(db.query('insert into auth.users(id,email,raw_user_meta_data) values ($1,$2,$3)',[incoming,'incoming@equicomtech.com',JSON.stringify({dm_employee_login_token:token})]),/Activate or restore/);
  assert.equal((await db.query('select count(*)::int as n from auth.users where id=$1',[incoming])).rows[0].n,0);
 }finally{await db.close();}
});
